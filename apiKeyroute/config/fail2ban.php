<?php

/*
|--------------------------------------------------------------------------
| Fail2Ban — محافظت در برابر سیل درخواست (Request Flood Protection)
|--------------------------------------------------------------------------
|
| این تنظیمات رفتار میدلوور App\Http\Middleware\RequestRateGuard را کنترل
| می‌کند. منطق کار شبیه fail2ban است:
|
|   ۱. تعداد درخواست هر IP در یک بازه‌ی لغزان (sliding window) شمرده می‌شود.
|   ۲. اگر از آستانه‌ی «عرفی» عبور کرد، آن IP برای چند دقیقه بن (بلاک) می‌شود.
|   ۳. تکرار تخلف در بازه‌ی کوتاه باعث تشدید مدت بن می‌شود (backoff نمایی).
|
| نکته درباره CDN: تشخیص IP از تابع getIp() انجام می‌شود که هدرهای مطمئن
| CDN (ar-real-ip / CF-Connecting-IP / X-Real-IP) را می‌خواند؛ بنابراین
| شمارش روی IP واقعیِ کاربر است، نه IP لبه‌ی CDN.
|
*/

return [

    // فعال/غیرفعال بودن کل مکانیزم. برای خاموش کردن سریع در شرایط اضطراری.
    'enabled' => env('FAIL2BAN_ENABLED', true),

    /*
    |----------------------------------------------------------------------
    | پنجره‌ی شمارش (Sliding Window)
    |----------------------------------------------------------------------
    | در هر «window» ثانیه، حداکثر «max_requests» درخواست از یک IP مجاز است.
    | این عدد باید بالاتر از throttle عادی (throttle:600,1) تنظیم شود تا فقط
    | ترافیک واقعاً غیرعرف را بگیرد، نه کاربر پرمصرفِ سالم.
    */
    'window'       => (int) env('FAIL2BAN_WINDOW', 60),
    'max_requests' => (int) env('FAIL2BAN_MAX_REQUESTS', 500),

    /*
    |----------------------------------------------------------------------
    | مدت بن و تشدید آن
    |----------------------------------------------------------------------
    | ban_seconds        : مدت بن برای اولین تخلف.
    | escalation_window  : اگر IP در این بازه دوباره تخلف کند، «strike» بعدی
    |                       ثبت و مدت بن دو برابر می‌شود (نمایی).
    | max_ban_seconds    : سقف مدت بن حتی با تشدید.
    */
    'ban_seconds'       => (int) env('FAIL2BAN_BAN_SECONDS', 600),      // ۱۰ دقیقه
    'escalation_window' => (int) env('FAIL2BAN_ESCALATION_WINDOW', 3600), // ۱ ساعت
    'max_ban_seconds'   => (int) env('FAIL2BAN_MAX_BAN_SECONDS', 21600), // ۶ ساعت

    /*
    |----------------------------------------------------------------------
    | تشخیص تقلب روی ارسال OTP (OTP Fraud Detection)
    |----------------------------------------------------------------------
    | میدلوور/نگهبان App\Support\Security\OtpFraudGuard روی هر IP یک پنجره‌ی
    | لغزان از شماره‌های امتحان‌شده نگه می‌دارد و سه نشانه را می‌سنجد. با
    | فعال‌شدن هرکدام، IP از طریق همین مکانیزم fail2ban (با تشدید نمایی) بن می‌شود.
    |
    |   window          : بازه‌ی بررسی الگو (ثانیه)
    |   ban_seconds     : مدت بن پایه برای اولین تخلف (تخلف مکرر → دوبرابر…)
    |
    |   max_distinct    : سقفِ تعداد شماره‌ی «متفاوت» از یک IP در پنجره (velocity)
    |   min_sequential  : حداقل طول دنباله‌ی متوالی برای صدور بن (...2070/2069/2068)
    |   max_gap         : بیشترین فاصله‌ی دو شماره تا هنوز «متوالی» حساب شوند
    |   prefix_len      : طول پیش‌شماره برای گروه‌بندی (رقم)
    |   min_prefix      : حداقل تعداد شماره با پیش‌شماره‌ی یکسان برای صدور بن
    */
    'otp_fraud' => [
        'enabled'        => (bool) env('FAIL2BAN_OTPFRAUD_ENABLED', true),
        'window'         => (int) env('FAIL2BAN_OTPFRAUD_WINDOW', 60),
        'ban_seconds'    => (int) env('FAIL2BAN_OTPFRAUD_BAN_SECONDS', 180), // ۳ دقیقه

        'max_distinct'   => (int) env('FAIL2BAN_OTPFRAUD_MAX_DISTINCT', 8),
        'min_sequential' => (int) env('FAIL2BAN_OTPFRAUD_MIN_SEQ', 4),
        'max_gap'        => (int) env('FAIL2BAN_OTPFRAUD_MAX_GAP', 2),
        'prefix_len'     => (int) env('FAIL2BAN_OTPFRAUD_PREFIX_LEN', 7),
        'min_prefix'     => (int) env('FAIL2BAN_OTPFRAUD_MIN_PREFIX', 5),
    ],

    /*
    |----------------------------------------------------------------------
    | لیست سفید (Whitelist)
    |----------------------------------------------------------------------
    | IPها یا رنج‌های CIDR که هرگز بن نمی‌شوند: IP لبه‌ی CDN، مانیتورینگ،
    | سرویس‌های شریک، دفتر و … . IPهای خصوصی/لوکال به‌صورت خودکار معاف‌اند.
    */
    'whitelist' => array_values(array_filter(array_map('trim', explode(',', (string) env('FAIL2BAN_WHITELIST', ''))))) ?: [
        // '79.127.14.25',
        // '94.182.190.0/24',
    ],

    /*
    |----------------------------------------------------------------------
    | مسیرهای معاف
    |----------------------------------------------------------------------
    | الگوهای مسیر (fnmatch) که از شمارش کنار گذاشته می‌شوند؛ مثل health-check.
    */
    'except_paths' => [
        'up',
        'telescope*',
        'horizon*',
        // وبهوک بات‌های پیام‌رسان (تلگرام/بله): بله/تلگرام IP ثابت منتشر نمی‌کنند،
        // امنیت این مسیر با secret_token تأمین می‌شود نه IP، پس نباید در معرض بن fail2ban باشد.
        'api/b2c/v1/bot/*',
    ],

    /*
    |----------------------------------------------------------------------
    | لاگ‌گیری رویداد بن
    |----------------------------------------------------------------------
    */
    'log_channel' => env('FAIL2BAN_LOG_CHANNEL', null), // null = کانال پیش‌فرض
];
